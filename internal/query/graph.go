// Graph is a time series: one value per series per bucket.
type Graph struct {
	Bucket        string      `json:"bucket"` // chosen size, e.g. "1m" (never "auto")
	BucketSeconds float64     `json:"bucketSeconds"`
	Starts        []time.Time `json:"starts"` // bucket start times, ascending
	Metric        Column      `json:"metric"`
	GroupBy       []string    `json:"groupBy,omitempty"` // group-by paths, one per Series.Group label
	Groups        int         `json:"groups"`            // groups before the top cut
	Top           int         `json:"top"`               // groups drawn on their own (the cut)
	Series        []Series    `json:"series"`            // in group order (count desc by default); "other" last
}

// Series is one line of a graph.
type Series struct {
	Label  string     `json:"label"` // group labels joined " · "; "all" with no group-by; "other"
	Group  []string   `json:"group"`
	Other  bool       `json:"other,omitempty"`
	Count  int        `json:"count"`
	Values []*float64 `json:"values"` // len == len(Starts); nil = no data
}

const (
	autoBucketLimit = 100
	maxGraphBuckets = 2000
)

var bucketSizes = map[string]time.Duration{
	"1s": time.Second, "5s": 5 * time.Second, "10s": 10 * time.Second, "30s": 30 * time.Second,
	"1m": time.Minute, "5m": 5 * time.Minute, "15m": 15 * time.Minute,
	"1h": time.Hour, "6h": 6 * time.Hour, "1d": 24 * time.Hour,
}

func bucketCount(span, size time.Duration) int64 {
	return int64((span + size - 1) / size)
}

// chooseBucket resolves a bucket name for a data span. "auto" (or empty)
// picks the smallest size giving at most 100 buckets; an explicit size errors
// when it would give more than 2000.
func chooseBucket(name string, span time.Duration) (time.Duration, string, error) {
	if name == "" || name == "auto" {
		if span <= 0 {
			return time.Second, "1s", nil
		}
		for _, n := range Buckets {
			size, ok := bucketSizes[n]
			if ok && bucketCount(span, size) <= autoBucketLimit {
				return size, n, nil
			}
		}
		return 24 * time.Hour, "1d", nil
	}
	size, ok := bucketSizes[name]
	if !ok {
		return 0, "", fmt.Errorf("bucket %q: want one of %s", name, strings.Join(Buckets, ", "))
	}
	if bucketCount(span, size) > maxGraphBuckets {
		return 0, "", fmt.Errorf("too many time buckets; pick a coarser granularity")
	}
	return size, name, nil
}

// bucketStart aligns t to a bucket boundary: sizes up to 1h truncate the
// absolute time; 6h and 1d count from local midnight in loc.
func bucketStart(t time.Time, size time.Duration, loc *time.Location) time.Time {
	if size <= time.Hour {
		return t.Truncate(size)
	}
	lt := t.In(loc)
	mid := time.Date(lt.Year(), lt.Month(), lt.Day(), 0, 0, 0, 0, loc)
	return mid.Add(lt.Sub(mid) / size * size)
}

// xAxis is the graph's bucketing, shared by graph and heatmap. timed holds
// records with a time. The x range is clipped to the data and to [from, to];
// a zero from or to leaves that side to the data. last is the end of that
// range; with no records, starts is empty and the bucket is chosen for a
// zero span.
func xAxis(timed []*record.Record, bucket string, from, to time.Time, loc *time.Location) (starts []time.Time, size time.Duration, name string, last time.Time, err error) {
	starts = []time.Time{}
	var first time.Time
	for _, r := range timed {
		if first.IsZero() || r.Time.Before(first) {
			first = r.Time
		}
		if last.IsZero() || r.Time.After(last) {
			last = r.Time
		}
	}
	if len(timed) == 0 {
		size, name, err = chooseBucket(bucket, 0)
		return starts, size, name, last, err
	}
	if !from.IsZero() && from.After(first) {
		first = from
	}
	if !to.IsZero() && to.Before(last) {
		last = to
	}
	if last.Before(first) {
		last = first
	}

	size, name, err = chooseBucket(bucket, last.Sub(first))
	if err != nil {
		return nil, 0, "", time.Time{}, err
	}

	// Starts are generated by stepping to the next boundary, so a DST day
	// that is not 24h long stays aligned.
	end := bucketStart(last, size, loc)
	for cur := bucketStart(first, size, loc); !cur.After(end); cur = bucketStart(cur.Add(size*3/2), size, loc) {
		starts = append(starts, cur)
		if len(starts) > maxGraphBuckets {
			return nil, 0, "", time.Time{}, fmt.Errorf("too many time buckets; pick a coarser granularity")
		}
	}
	return starts, size, name, last, nil
}

// bucketIndex is the index of the bucket holding t: the last start at or
// before t, or 0 when t is before every start. starts must not be empty.
func bucketIndex(starts []time.Time, t time.Time) int {
	return max(sort.Search(len(starts), func(i int) bool { return starts[i].After(t) })-1, 0)
}

// runGraph buckets the timed matched records. The x range is clipped to the
// data and to [from, to]; a zero from or to leaves that side to the data.
func runGraph(matched []*record.Record, s schema.Schema, q Query, from, to time.Time, loc *time.Location) (*Graph, error) {
	plot := Aggregate{Op: "count"}
	if q.Plot != nil {
		plot = *q.Plot
	}
	g := &Graph{Metric: metricColumn(plot, s), GroupBy: append([]string(nil), q.GroupBy...), Starts: []time.Time{}, Series: []Series{}}

	var timed []*record.Record
	for _, r := range matched {
		if !r.Time.IsZero() {
			timed = append(timed, r)
		}
	}
	starts, size, name, last, err := xAxis(timed, q.Bucket, from, to, loc)
	if err != nil {
		return nil, err
	}
	g.Starts, g.Bucket, g.BucketSeconds = starts, name, size.Seconds()
	if len(timed) == 0 {
		return g, nil
	}

	// Group the records, then rank groups by the order metric (count by
	// default) over the whole range.
	gfields := make([]schema.Field, len(q.GroupBy))
	for i, p := range q.GroupBy {
		gfields[i] = lookupField(s, p)
	}
	type grp struct {
		key    string
		labels []string
		recs   []*record.Record
	}
	var groups []*grp
	byKey := map[string]*grp{}
	for _, r := range timed {
		if r.Time.Before(g.Starts[0]) || r.Time.After(last) {
			continue
		}
		key, labels, _ := groupKey(r, gfields)
		x := byKey[key]
		if x == nil {
			x = &grp{key: key, labels: labels}
			byKey[key] = x
			groups = append(groups, x)
		}
		x.recs = append(x.recs, r)
	}
	rankGroups(groups, func(x *grp) ([]*record.Record, string) { return x.recs, x.key }, q.Order, s)

	var plotField schema.Field
	if plot.Op != "count" {
		plotField = metricField(s, plot)
	}
	build := func(label string, labels []string, other bool, recs []*record.Record) Series {
		per := make([][]*record.Record, len(g.Starts))
		for _, r := range recs {
			i := bucketIndex(g.Starts, r.Time)
			per[i] = append(per[i], r)
		}
		vals := make([]*float64, len(g.Starts))
		for i, rs := range per {
			if plot.Op == "count" {
				v := float64(len(rs))
				vals[i] = &v
				continue
			}
			if v, ok := metricValue(rs, plot, plotField); ok && !math.IsNaN(v) && !math.IsInf(v, 0) {
				vals[i] = &v
			}
		}
		if labels == nil {
			labels = []string{}
		}
		return Series{Label: label, Group: labels, Other: other, Count: len(recs), Values: vals}
	}

	if len(gfields) == 0 {
		if len(groups) > 0 {
			g.Series = append(g.Series, build("all", nil, false, groups[0].recs))
		}
		return g, nil
	}
	top := q.Top
	if top <= 0 {
		top = DefaultTop
	}
	top = min(top, MaxGraphTop)
	g.Groups, g.Top = len(groups), top
	for i, x := range groups {
		if i >= top {
			break
		}
		g.Series = append(g.Series, build(strings.Join(x.labels, " · "), x.labels, false, x.recs))
	}
	if len(groups) > top {
		var rest []*record.Record
		for _, x := range groups[top:] {
			rest = append(rest, x.recs...)
		}
		g.Series = append(g.Series, build("other", nil, true, rest))
	}
	return g, nil
}
